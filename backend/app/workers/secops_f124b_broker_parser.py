# Explicitly synthetic subject and tenant, never inferred from untrusted input.
SYNTHETIC_TENANT = "synthetic-f124"
SYNTHETIC_USER = "11111111-1111-4111-8111-111111111111"
LAB_OPT_IN = "I_OWN_THIS_SYNTHETIC_PARSER_LAB"
_PARSER_SLOTS = threading.BoundedSemaphore(2)
_SAFE_ENV = {"PATH": "/usr/bin:/bin", "HOME": "/nonexistent"}


class SyntheticDispatchRejected(Exception):
    """Opaque error codes only; no data, names, identities or payload in repr."""

    def __init__(self, code: str = "F124B_DENIED") -> None:
        self.code = code
        super().__init__(code)


@dataclass(frozen=True)
class SyntheticDispatchResult:
    """Only a minimal summary; never return extracted text or documents."""

    request_digest: str
    format: str
    sections_detected: tuple[str, ...]
    item_count: int


def _fixture_allowed(job: ValidatedJob) -> bool:
    if (
        job.operation != "submit"
        or job.tenant_id != SYNTHETIC_TENANT
        or str(job.user_id) != SYNTHETIC_USER
        or job.document is None
        or job.filename is None
    ):
        return False
    # Whitelist EXACT fixture bytes and filename; disallow forged labels, even
    # valid PDFs/DOCXs written by someone outside the synthetic fixture factory.
    digest = hashlib.sha256(job.document).digest()
    return any(
        allowed
        and job.filename == name
        and hashlib.sha256(data).digest() == digest
        and data == job.document
        for name, data, _format, allowed in synthetic_cases()
    )


def _isolated_parser(job: ValidatedJob) -> dict[str, Any]:
    """Use existing bounded restricted Docker invocation, never host mounts."""
    assert job.filename is not None and job.document is not None
    name = "jobagent-f124b-synthetic-" + os.urandom(8).hex()
    try:
        result = _run_bounded(
            _container_command(name), parser_request(job.filename, job.document), _SAFE_ENV
        )
        if result.returncode != 0 or len(result.stdout) > MAX_WORKER_OUTPUT:
            raise SyntheticDispatchRejected("F124B_EXECUTOR_UNAVAILABLE")
        parsed: Any = json.loads(result.stdout)
        if not isinstance(parsed, dict):
            raise SyntheticDispatchRejected("F124B_EXECUTOR_UNAVAILABLE")
        return parsed
    except (OSError, subprocess.TimeoutExpired, ValueError, UnicodeError):
        raise SyntheticDispatchRejected("F124B_EXECUTOR_UNAVAILABLE") from None
    finally:
        _cleanup_container(name)


def operational_attestation() -> bool:
    """Opt-in full 12/12 operational test: NO-GO in unconfined Codespaces."""
    if os.environ.get("SECOPS_F124_ACK") != LAB_OPT_IN:
        return False
    try:
        checks = run_synthetic_parser_lab()
    except Exception:
        return False
    return len(checks) == 12 and all(checks.values())


def dispatch_synthetic_authenticated(
    connection: socket.socket,
    *,
    gate: BrokerTransportGate,
    attestation: Callable[[], bool] = operational_attestation,
    executor: Callable[[ValidatedJob], dict[str, Any]] = _isolated_parser,
) -> SyntheticDispatchResult:
    """One already accepted gateway connection, authenticated before execution.

    This is only a closed prototype/test seam, not a deployable socket service.
    Production user/tenant authority MUST NOT be emulated by this synthetic gate.
    """
    try:
        raw_frame = read_frame(connection)
        raw, service, timestamp, nonce, signature = _decode_frame(raw_frame)
        forward = gate.admit(
            connection,
            raw,
            service_id=service,
            timestamp=timestamp,
            nonce=nonce,
            signature=signature,
        )
        job = validate_job_envelope(raw)
    except (OSError, BrokerTransportRejected, ChainRejected, ProtocolValidationError):
        raise SyntheticDispatchRejected() from None
    if (
        forward.operation != "submit"
        or forward.tenant_id != SYNTHETIC_TENANT
        or forward.user_id != SYNTHETIC_USER
        or not _fixture_allowed(job)
    ):
        raise SyntheticDispatchRejected()

    # Do not start anything before authenticating transport, validating the
    # synthetic-only subject and checking the current runtime isolation proof.
    try:
        isolated = attestation() is True
    except Exception:
        isolated = False
    if not isolated:
        raise SyntheticDispatchRejected("F124B_SANDBOX_REQUIRED")
    if not _PARSER_SLOTS.acquire(blocking=False):
        raise SyntheticDispatchRejected("F124B_BUSY")
    try:
        response = executor(job)
    except SyntheticDispatchRejected:
        raise
    except Exception:
        raise SyntheticDispatchRejected("F124B_EXECUTOR_UNAVAILABLE") from None
    finally:
        _PARSER_SLOTS.release()
    if response.get("ok") is not True or not isinstance(response.get("preview"), dict):
        raise SyntheticDispatchRejected("F124B_EXECUTOR_UNAVAILABLE")
    preview = response["preview"]
    fmt = preview.get("format")
    sections = preview.get("sections_detected")
    items = preview.get("items")
    if (
        fmt not in {"pdf", "docx", "txt"}
        or fmt != job.filename.rsplit(".", 1)[-1]
        or not isinstance(sections, list)
        or not all(isinstance(s, str) and len(s) <= 40 for s in sections)
        or len(sections) > 16
        or not isinstance(items, list)
        or len(items) > 40
    ):
        raise SyntheticDispatchRejected("F124B_EXECUTOR_UNAVAILABLE")
    return SyntheticDispatchResult(
        request_digest=forward.digest,
        format=fmt,
        sections_detected=tuple(sections),
        item_count=len(items),
    )
